// Bundles knowledge/*.md into api/_knowledge.js as an array of {source, text}
// chunks, so the serverless function has no filesystem dependency.
// Run `npm run sync` after editing any knowledge file.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const kdir = join(root, "knowledge");

const chunks = [];
for (const file of readdirSync(kdir).filter((f) => f.endsWith(".md")).sort()) {
  const source = file.replace(/\.md$/, "");
  const text = readFileSync(join(kdir, file), "utf8");
  // Split on markdown headings; keep each heading with its body.
  for (let part of text.split(/\n(?=#{1,3} )/)) {
    part = part.trim();
    if (part.length < 40) continue;
    if (part.length > 1500) {
      // Further split very long sections on blank lines.
      let buf = "";
      for (const para of part.split("\n\n")) {
        if (buf.length + para.length > 1200 && buf) {
          chunks.push({ source, text: buf.trim() });
          buf = "";
        }
        buf += para + "\n\n";
      }
      if (buf.trim().length >= 40) chunks.push({ source, text: buf.trim() });
    } else {
      chunks.push({ source, text: part });
    }
  }
}

const out = `// AUTO-GENERATED by scripts/bundle.mjs — do not edit by hand.
// Source of truth: agent/knowledge/*.md
export const CHUNKS = ${JSON.stringify(chunks, null, 0)};
`;

writeFileSync(join(root, "api", "_knowledge.js"), out);
console.log(`bundled ${chunks.length} chunks from knowledge/ -> api/_knowledge.js`);
